const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {chromium}=require('playwright');
const root=path.resolve(__dirname,'..');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1100}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.setContent('<!doctype html><meta charset="utf-8"><style>body{margin:24px;background:#e9ece5}</style><div class="functions-container"></div>');
 await page.addScriptTag({content:fs.readFileSync(path.join(__dirname,'mock-kano.js'),'utf8')});
 await page.addScriptTag({content:fs.readFileSync(path.join(root,'dist/tunnel-studio.js'),'utf8')});
 const action=a=>page.locator('[data-action="'+a+'"]');
 const tab=a=>page.locator('[data-tab="'+a+'"]');
 await page.locator('#kano-tunnel-studio').waitFor();
 assert.equal(await action('start').isDisabled(),true);
 await tab('diagnostics').click();await action('preflight').click();await page.getByText('执行通道检查完成。',{exact:true}).waitFor();
 await tab('recovery').click();await action('install').click();await page.locator('#accept').click();
 await page.getByText('资源已安装。可导入配置后校验。',{exact:true}).waitFor();
 assert.equal(await page.evaluate(()=>KTS_MOCK.installed),true);
 await page.evaluate(()=>{KTS_MOCK.installed=true;KTS_MOCK.profile={protocol:'amneziawg',text:'[Interface]\nPrivateKey = <test-only>\nAddress = 10.1.0.2/32',sources:[]};});
 await tab('overview').click();await action('refresh').click();await page.getByText('设备状态已刷新。',{exact:true}).waitFor();
 assert.equal(await action('start').isEnabled(),true);
 await action('start').click();await page.locator('#cancel').click();assert.equal(await page.evaluate(()=>KTS_MOCK.running),false);
 await action('start').click();await page.locator('#accept').click();await page.getByText('隧道已启动，请查看握手状态。',{exact:true}).waitFor();
 assert.equal(await action('start').isDisabled(),true);assert.equal(await page.locator('#rx').textContent(),'10.0 KiB');
 await page.screenshot({path:path.join(root,'docs/desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});await page.locator('.mode').selectOption('phone');
 await page.screenshot({path:path.join(root,'docs/phone.png'),fullPage:true});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'phone layout overflows');
 await action('stop').click();await page.getByText('本插件隧道已停止。',{exact:true}).waitFor();
 await tab('profile').click();await action('load').click();await page.locator('#accept').click();await page.getByText('设备配置已载入内存。',{exact:true}).waitFor();
 await page.locator('#config').fill('[Interface]\nPrivateKey = <changed-test-only>');
 await tab('overview').click();assert.equal(await action('start').isDisabled(),true);
 await tab('profile').click();await action('save').click();await page.getByText('已保存；旧配置已自动创建快照。',{exact:true}).waitFor();
 await page.locator('#config').fill('invalid');await action('validate').click();await page.locator('.message.error').waitFor();
 assert.match(await page.locator('.message').textContent(),/PrivateKey/);
 // An imported draft must also block starting the previously saved profile.
 const importing=page.locator('#import').setInputFiles({name:'draft.conf',mimeType:'text/plain',buffer:Buffer.from('[Interface]\nPrivateKey = <draft-only>')});
 await importing;await page.locator('#accept').click();await page.getByText('已导入到编辑器，请检查协议并校验。',{exact:true}).waitFor();
 await tab('overview').click();assert.equal(await action('start').isDisabled(),true);
 await page.evaluate(()=>{KTS_MOCK.backups=['<img src=x onerror=alert(1)>.json'];});
 await tab('recovery').click();await action('backups').click();await page.getByText('<img src=x onerror=alert(1)>.json',{exact:true}).waitFor();assert.equal(await page.locator('#backups img').count(),0);
 assert.deepEqual(errors,[]);
 fs.writeFileSync(path.join(root,'docs/browser-results.json'),JSON.stringify({passed:true,checks:['desktop and phone layout','root bridge probe','explicit start confirmation','status counters','running controls','unsaved edits and imports prevent start','save and validation errors','backup names rendered as text'],pageErrors:errors},null,2));
 await browser.close();console.log('Browser workflow tests passed');
})().catch(e=>{console.error(e);process.exit(1)});
